"""Private learned routines, generated CLI-only scripts and durable per-step execution."""
import copy
import json
from pathlib import Path
import time
import uuid

from .contexts import directory, name, read, write
from .errors import BlinkError
from .runtime import envelope
from .storage import digest
from .verification import binding_identity, proof_identity


def reject_dependencies(steps, operations):
    """Until reviewed result references exist, no step may follow a mutation.

    Inferring dependencies from literal equality misses embedded or transformed IDs.
    Reads may precede a final mutation; its correlated read-back remains supported.
    """
    if any(operations[step['operation']]['effect'] != 'read' for step in steps[:-1]):
        raise BlinkError('unsupported_dependency', 'Steps after a mutation require reviewed result references; save the mutation as the final step')


def normalized(phrase):
    if not isinstance(phrase, str) or not 1 <= len(phrase.strip()) <= 500:
        raise BlinkError('invalid_arguments', 'A routine phrase is required')
    return ' '.join(phrase.casefold().split())


def revision(value):
    return digest({k: v for k, v in value.items() if k != 'history'})


def resolve_service(key):
    """Resolve a local routine before the CLI reads per-Blink settings such as dry-run."""
    from .home import home_dir
    matches = list((home_dir() / 'routines').glob('*/' + name(key) + '.json'))
    if len(matches) != 1:
        raise BlinkError('ambiguous_routine', 'Name the exact service for this routine')
    return read(matches[0])['service']


def script_source(service, routine, count, delay):
    """No recorded values, credentials, HTTP client, eval or shell interpolation in generated code."""
    return '''#!/usr/bin/env python3
"""Generated by Web Blink. Each operation goes through the JSON CLI and its durable run journal."""
import json
import subprocess
import sys
import time

def main():
    run_id = sys.argv[1]
    results = []
    for index in range(COUNT):
        if index:
            time.sleep(DELAY / 1000)
        params = {'service': SERVICE, 'name': ROUTINE, 'runId': run_id, 'index': index}
        for attempt in range(4):
            response = subprocess.run([sys.executable, '-c', CLI_CODE, '--output', 'json', 'routine', 'step', '--yes', '--input', json.dumps(params)],
                                      capture_output=True, text=True, check=False)
            try:
                result = json.loads(response.stdout)
            except ValueError:
                result = {'status': 'outcome_unknown', 'summary': 'CLI reply unavailable; inspect this run before resuming'}
            # Only the daemon may mark a proven-unsent call or a read safe to retry.
            if not result.get('retrySafe') or attempt == 3:
                break
            time.sleep(min(500, DELAY * (2 ** (attempt + 1))) / 1000)
        results.append(result)
        if result.get('status') != 'ok':
            print(json.dumps(result))
            return 1
    print(json.dumps({'status': 'ok', 'summary': 'Routine completed and verified', 'data': {'runId': run_id, 'steps': results}}))
    return 0

SERVICE = SERVICE_VALUE
CLI_CODE = CLI_CODE_VALUE
ROUTINE = ROUTINE_VALUE
COUNT = COUNT_VALUE
DELAY = DELAY_VALUE
if __name__ == '__main__':
    raise SystemExit(main())
'''.replace('SERVICE_VALUE', repr(service)).replace('ROUTINE_VALUE', repr(routine)).replace('COUNT_VALUE', str(count)).replace('DELAY_VALUE', str(delay)).replace(
    'CLI_CODE_VALUE', repr('import sys; sys.path.insert(0, ' + repr(str(Path(__file__).resolve().parents[1])) +
                          '); from blink.cli import main; raise SystemExit(main())'))


class Routines:
    def __init__(self, extensions):
        self.extensions, self.runtime = extensions, extensions.runtime

    def load(self, service, key):
        value = read(directory('routines', service) / (name(key) + '.json'))
        if not value:
            raise BlinkError('unknown_routine', 'Routine was not found')
        return value

    def list(self, service):
        return [read(p) for p in sorted(directory('routines', service).glob('*.json'))]

    def lookup(self, p):
        wanted = normalized(p['phrase'])
        matches = [r for r in self.list(p['service']) if wanted in {normalized(r['phrase']), *(normalized(a) for a in r['aliases'])}]
        if len(matches) > 1:
            raise BlinkError('ambiguous_routine', 'More than one routine has that phrase')
        return self.plan({'service': p['service'], 'name': matches[0]['name']}) if matches else envelope('unknown_routine', 'Demonstrate this task once to learn its rules')

    def save(self, p):
        if set(p) - {'service', 'name', 'phrase', 'aliases', 'previewBeforeCommit', 'verificationIds', 'delayMs', 'context'}:
            raise BlinkError('invalid_arguments', 'Routines are generated from verificationIds, never arbitrary scripts or steps')
        service, key = p.get('service'), name(p.get('name'))
        normalized(p.get('phrase'))
        aliases = p.get('aliases', [])
        if not isinstance(aliases, list) or len(aliases) > 20:
            raise BlinkError('invalid_arguments', 'At most twenty aliases are allowed')
        phrases = {normalized(p['phrase']), *(normalized(a) for a in aliases)}
        for other in self.list(service):
            if other['name'] != key and phrases & {normalized(other['phrase']), *(normalized(a) for a in other['aliases'])}:
                raise BlinkError('ambiguous_routine', 'This phrase already belongs to another routine')
        delay = p.get('delayMs', 100)
        if type(delay) is not int or not 50 <= delay <= 500 or type(p.get('previewBeforeCommit', False)) is not bool:
            raise BlinkError('invalid_arguments', 'delayMs must be 50–500; previewBeforeCommit must be a boolean')
        ids = p.get('verificationIds')
        if (not isinstance(ids, list) or not 1 <= len(ids) <= 100 or any(not isinstance(v, str) for v in ids)
                or len(set(ids)) != len(ids)):
            raise BlinkError('invalid_arguments', 'Select one to one hundred verified calls, in execution order')
        active = self.runtime.active_manifest(service)
        steps, executed = [], set()
        for proof_id in ids:
            proof = self.runtime.store.get('verified_call', proof_id)
            verification = self.runtime.store.get('verification', proof_id)
            if (not proof or not verification or verification.get('verification') != 'verified'
                    or proof['service'] != service or proof['manifestDigest'] != active['digest']):
                raise BlinkError('verification_required', 'Every routine step must have current, successful execution evidence')
            event = ('capture', proof['observed']['session'], proof['observed']['seq']) if proof.get('observed') else (
                ('intent', proof['intentId']) if proof.get('intentId') else ('read', proof_id))
            if event in executed:
                raise BlinkError('verification_required', 'Each demonstrated execution may supply only one routine step')
            executed.add(event)
            binding = proof_identity(self.runtime, proof)
            verify = copy.deepcopy(proof['verification'])
            if verify.get('correlation'):
                response_path = verify['correlation'].get('responsePath', verify['correlation']['path'])
                verify['correlatedExpectedPaths'] = [c['path'] for c in verification['checks'] if c['path'] == response_path and c['matched']]
            operation, arguments = verify['operation'], verify['arguments']
            if proof.get('observed'):
                operation, arguments = proof['observed']['operation'], proof['observed']['arguments']
            elif proof.get('intentId'):
                with self.runtime.store.transaction() as db:
                    row = db.execute('SELECT * FROM intents WHERE id=?', (proof['intentId'],)).fetchone()
                if not row or row['state'] not in ('succeeded', 'resolved_done'):
                    raise BlinkError('outcome_unknown', 'Reconcile the original mutation before saving a routine')
                if row['binding'] != proof.get('binding') or row['service'] != service or row['digest'] != active['digest']:
                    raise BlinkError('account_mismatch', 'Use verification for the original intent account and manifest')
                self.runtime._intent_identity(row, binding)
                operation, arguments = row['operation'], json.loads(row['args_json'])
            op = active['compiled']['operations'][operation]
            if op['effect'] != 'read' and not (proof.get('intentId') or proof.get('observed')):
                raise BlinkError('verification_required', 'A mutation needs its original intent and correlated read-back')
            self.runtime._validate_argument_values(arguments)
            # Credential field names/values are rejected rather than copied or silently redacted.
            self.runtime._validate_argument_values({'verification': verify})
            steps.append({'operation': operation, 'arguments': copy.deepcopy(arguments), 'binding': proof.get('binding'),
                          'operationDigest': op['digest'], 'verification': verify, 'proofId': proof_id,
                          'bindingIdentity': copy.deepcopy(proof.get('bindingIdentity'))})
        reject_dependencies(steps, active['compiled']['operations'])
        if p.get('context'):
            context = self.extensions.execution.contexts.choose(service, context=p['context'])
            if any(s['binding'] != context['binding'] for s in steps):
                raise BlinkError('account_mismatch', 'All routine steps must use the selected context account')
        path = directory('routines', service) / (key + '.json')
        previous = read(path)
        history = (previous or {}).get('history', [])
        value = {'service': service, 'name': key, 'phrase': p['phrase'], 'aliases': aliases,
                 'previewBeforeCommit': p.get('previewBeforeCommit', False), 'steps': steps,
                 'manifestDigest': active['digest'], 'delayMs': delay, 'context': p.get('context'),
                 'history': history + [{'event': 'saved', 'at': time.time(), 'proofIds': ids,
                                        'previousDigest': digest(previous) if previous else None}]}
        # Immutable script revisions keep an already-authorized run usable while its routine is edited.
        source = script_source(service, key, len(steps), delay)
        script = directory('scripts', service) / (key + '-' + digest(source)[:12] + '.py')
        value['script'] = str(script)
        value['scriptDigest'] = digest(source)
        write(script, source)
        write(path, value)
        return envelope('ok', 'Routine and deterministic CLI script saved locally', value)

    def _current(self, value):
        record = self.runtime.active_manifest(value['service'])
        if value['manifestDigest'] != record['digest']:
            raise BlinkError('approval_stale', 'The Blink changed; verify and save this routine again')
        reject_dependencies(value['steps'], record['compiled']['operations'])
        for step in value['steps']:
            binding = self.runtime.store.get('binding', step['binding']) if step['binding'] else None
            identity = binding_identity(binding)
            if identity != step['bindingIdentity'] or binding and binding.get('state') == 'revoked':
                raise BlinkError('account_mismatch', 'A routine account changed; verify and save the routine again')
        return record

    def plan(self, p):
        value = self.load(p['service'], p['name'])
        record = self._current(value)
        instructions = [self.runtime._describe_notes(record, record['compiled']['operations'][s['operation']]) for s in value['steps']]
        plan = {'routineDigest': revision(value), 'instructions': instructions}
        data = {'name': value['name'], 'service': value['service'], 'planDigest': digest(plan),
                'question': 'Should I do this according to the last rules?', 'instructions': instructions,
                'previewBeforeCommit': value['previewBeforeCommit']}
        if value['previewBeforeCommit']:
            data['preview'] = [{k: s[k] for k in ('operation', 'arguments', 'binding')} for s in value['steps']]
        return envelope('confirmation_required', 'Confirm the known routine once', data)

    def begin(self, p):
        plan = self.plan(p)
        if p.get('confirmed') is not True:
            return plan
        if p.get('planDigest') != plan['data']['planDigest']:
            raise BlinkError('approval_stale', 'Confirm the current routine and instructions before running it')
        value = self.load(p['service'], p['name'])
        key = p.get('runId') or uuid.uuid4().hex
        name(key)
        old = self.runtime.store.get('routine_run', key)
        if old:
            if old['routineDigest'] != revision(value) or old['service'] != p['service'] or old['name'] != p['name']:
                raise BlinkError('intent_conflict', 'Run ID already belongs to another routine revision')
            return envelope('ok', 'Existing routine run retained', old)
        run = {'id': key, 'service': value['service'], 'name': value['name'], 'routineDigest': revision(value),
               'routine': value, 'planDigest': plan['data']['planDigest'], 'state': 'running', 'steps': [], 'createdAt': time.time()}
        self.runtime.store.put('routine_run', key, run)
        return envelope('ok', 'Routine run authorized', run)

    def step(self, p):
        run = self.runtime.store.get('routine_run', p.get('runId'))
        if not run or run['service'] != p.get('service') or run['name'] != p.get('name'):
            raise BlinkError('unknown_routine_run', 'Start and confirm this routine before running its script')
        value = run['routine']
        record = self._current(value)
        instructions = [self.runtime._describe_notes(record, record['compiled']['operations'][s['operation']]) for s in value['steps']]
        if digest({'routineDigest': run['routineDigest'], 'instructions': instructions}) != run['planDigest']:
            raise BlinkError('approval_stale', 'Routine instructions changed after confirmation; stop before the next step')
        index = p.get('index')
        if type(index) is not int or not 0 <= index < len(value['steps']):
            raise BlinkError('invalid_arguments', 'Invalid routine step')
        if index < len(run['steps']):
            prior = run['steps'][index]
            if prior['status'] not in ('retryable', 'login_wait'):
                return prior['result'] if 'result' in prior else envelope('outcome_unknown', 'Inspect this interrupted step; its mutation will not be replayed', {'runId': run['id'], 'index': index})
        elif index != len(run['steps']):
            raise BlinkError('invalid_arguments', 'Run routine steps in order')
        elif index:
            if run['steps'][index - 1]['status'] != 'ok':
                raise BlinkError('outcome_unknown', 'The preceding routine step is unfinished')
        step = value['steps'][index]
        params = {k: copy.deepcopy(step[k]) for k in ('operation', 'arguments', 'verification')}
        params['service'] = value['service']
        if step['binding']:
            params['binding'] = step['binding']
        if value.get('context'):
            params['context'] = value['context']
        params['requestId'] = 'routine-' + digest({'run': run['id'], 'index': index})[:40]
        if p.get('requestId', params['requestId']) != params['requestId']:
            raise BlinkError('intent_conflict', 'Resume the original routine step request ID')
        if index < len(run['steps']) and run['steps'][index]['status'] == 'login_wait':
            params['visible'] = True
            params['context'] = run['steps'][index]['resumeContext']
        journal = {'status': 'dispatching'}
        if index < len(run['steps']):
            run['steps'][index] = journal
        else:
            run['steps'].append(journal)
        self.runtime.store.put('routine_run', run['id'], run)  # Persist before any request can escape.
        result = self.extensions.execution.run(params)
        error = (result.get('data') or {}).get('error', {}) if isinstance(result.get('data'), dict) else {}
        effect = self.runtime.active_manifest(value['service'])['compiled']['operations'][step['operation']]['effect']
        retry = result['status'] == 'rate_limited' and (effect == 'read' or error.get('dispatched') is False)
        verified = result.get('verification', {}).get('verification') == 'verified'
        status = 'ok' if verified and result['status'] in ('ok', 'succeeded', 'resolved_done') else result['status']
        if status in ('ok', 'succeeded', 'resolved_done') and not verified:
            status = 'unverified'
        output = {**result, 'status': status, 'retrySafe': retry, 'runId': run['id'], 'index': index}
        action = (result.get('data') or {}).get('nextAction', {}) if isinstance(result.get('data'), dict) else {}
        login_wait = status == 'login_required' and action.get('method') == 'execution_run' and action.get('params', {}).get('requestId') == params['requestId']
        if login_wait:
            with self.runtime.store.transaction() as db:
                intent = db.execute('SELECT state FROM intents WHERE id=?', (params['requestId'],)).fetchone()
            login_wait = not intent or intent['state'] in ('prepared', 'approved')
        if login_wait:
            journal['resumeContext'] = action['params']['context']
            output['data']['nextAction'] = {'method': 'routine_step', 'params': {
                'service': run['service'], 'name': run['name'], 'runId': run['id'], 'index': index,
                'requestId': params['requestId'], 'visible': True}}
        journal.update(status='login_wait' if login_wait else 'retryable' if retry else status, result=output)
        run['state'] = 'waiting_for_login' if login_wait else 'succeeded' if status == 'ok' and index == len(value['steps']) - 1 else 'running' if status == 'ok' or retry else 'stopped'
        self.runtime.store.put('routine_run', run['id'], run)
        current = self.load(value['service'], value['name'])
        current['history'].append({'event': 'step', 'runId': run['id'], 'index': index, 'status': status, 'at': time.time()})
        write(directory('routines', value['service']) / (value['name'] + '.json'), current)
        return output

    def run(self, p):
        """MCP uses the same journal and CLI-script semantics, without calling back into its locked daemon."""
        started = self.begin(p)
        if started['status'] != 'ok':
            return started
        run = started['data']
        results = []
        for index in range(len(run['routine']['steps'])):
            if index:
                time.sleep(run['routine']['delayMs'] / 1000)
            for attempt in range(4):
                result = self.step({'service': run['service'], 'name': run['name'], 'runId': run['id'], 'index': index})
                if not result.get('retrySafe') or attempt == 3:
                    break
                time.sleep(min(500, run['routine']['delayMs'] * 2 ** (attempt + 1)) / 1000)
            results.append(result)
            if result['status'] != 'ok':
                return result
        return envelope('ok', 'Routine completed and verified', {'runId': run['id'], 'steps': results})
